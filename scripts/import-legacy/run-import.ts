import postgres from "postgres";
import { buildPlan, planMovementCategories, type Plan, type PlanOptions, type Row } from "./build-plan";
import type { LegacyData } from "./legacy-reader";
import { LegacyDataError, mapPaymentMethod } from "./mapping";
import { reconcile, type Reconciliation } from "./reconcile";

type Tx = postgres.TransactionSql;

/** Imported business tables, children first is irrelevant: one TRUNCATE statement handles the FK graph. */
const BUSINESS_TABLES = [
  "stock_movements", "stock_levels", "recipe_components", "sale_order_lines", "movements", "sale_orders",
  "cash_events", "cash_movements", "cash_sessions", "products", "suppliers", "product_categories", "users",
] as const;

export interface RunOptions {
  replace: boolean;
  dryRun: boolean;
}

export interface RunResult {
  plan: Plan;
  reconciliation: Reconciliation;
  skippedCategories: { name: string; kind: string; reason: string }[];
  categoriesInserted: number;
  categoriesActiveUpdated: number;
  replaced: Record<string, number>;
  committed: boolean;
}

const CHUNK = 1000;

async function insertRows(tx: Tx, table: string, rows: Row[]): Promise<void> {
  if (rows.length === 0) return;
  const columns = Object.keys(rows[0]);
  for (let i = 0; i < rows.length; i += CHUNK) {
    await tx`insert into ${tx(table)} ${tx(rows.slice(i, i + CHUNK), ...columns)}`;
  }
}

/** Identity columns are GENERATED ALWAYS; keep the legacy numbers by switching to BY DEFAULT only inside this transaction. */
async function insertWithNumbers(tx: Tx, table: string, rows: Row[]): Promise<void> {
  if (rows.length === 0) return;
  await tx.unsafe(`alter table ${table} alter column number set generated by default`);
  await insertRows(tx, table, rows);
  await tx.unsafe(`alter table ${table} alter column number set generated always`);
}

/** setval is not transactional, so it runs only once the import is certain to commit (never on dry-run / mismatch). */
async function syncIdentity(tx: Tx, table: string): Promise<void> {
  await tx.unsafe(`select setval(pg_get_serial_sequence('${table}', 'number'), (select max(number) from ${table}), true)`);
}

async function nonEmptyBusinessTables(tx: Tx): Promise<Record<string, number>> {
  const found: Record<string, number> = {};
  for (const table of BUSINESS_TABLES) {
    // The default "General" product category is seeded reference data, not business data.
    const where = table === "product_categories" ? "where lower(name) <> 'general'" : "";
    const n = Number((await tx.unsafe(`select count(*)::int as n from ${table} ${where}`))[0].n);
    if (n > 0) found[table] = n;
  }
  return found;
}

async function lookup(tx: Tx, table: string, key: string): Promise<Map<string, string>> {
  const rows = await tx.unsafe(`select id, ${key} as k from ${table}`);
  return new Map(rows.map((r) => [String(r.k), String(r.id)]));
}

export async function runImport(sql: postgres.Sql, legacy: LegacyData, options: RunOptions): Promise<RunResult> {
  const unsupported = Object.entries(legacy.unsupportedCounts).filter(([, n]) => n > 0);
  if (unsupported.length) {
    throw new LegacyDataError(
      `Legacy data this importer does not map yet: ${unsupported.map(([t, n]) => `${t}=${n}`).join(", ")}. Aborting instead of guessing.`,
    );
  }
  // Reference data is never created here: the target must have been seeded (pnpm db:seed).
  const paymentNames = [...new Set(legacy.metodosPago.map((m) => mapPaymentMethod(String(m.nombre))?.name).filter((n): n is string => !!n))];

  const holder: { value: RunResult | null } = { value: null };
  class DryRunRollback extends Error {}
  try {
    await sql.begin(async (tx) => {
      await tx`select pg_advisory_xact_lock(hashtext('chusetts-import-legacy'))`;
      const business = await nonEmptyBusinessTables(tx);
      const replaced: Record<string, number> = {};
      if (Object.keys(business).length > 0) {
        if (!options.replace) {
          throw new LegacyDataError(
            `Target already contains business data (${Object.entries(business).map(([t, n]) => `${t}=${n}`).join(", ")}). Re-run with --replace to truncate the imported business tables.`,
          );
        }
        await tx.unsafe(`truncate table ${BUSINESS_TABLES.join(", ")} restart identity`);
        Object.assign(replaced, business);
      }

      // Reference data (units, payment methods, movement categories) must be seeded.
      const units = await lookup(tx, "units", "code");
      const paymentMethodsByName = await lookup(tx, "payment_methods", "name");
      const paymentMethods = await lookup(tx, "payment_methods", "code");
      for (const name of paymentNames) {
        if (!paymentMethodsByName.has(name)) throw new LegacyDataError(`Payment method "${name}" is missing in the target (run pnpm db:seed).`);
      }
      for (const u of legacy.unidades) {
        if (!units.has(String(u.codigo))) throw new LegacyDataError(`Unit "${String(u.codigo)}" is missing in the target (run pnpm db:seed).`);
      }

      // Movement categories: match by name, insert the missing ones, mirror the legacy `activo` flag.
      const existingCategories = await lookup(tx, "movement_categories", "name");
      const categoryPlan = planMovementCategories(legacy, existingCategories);
      await insertRows(tx, "movement_categories", categoryPlan.insert);
      for (const { id, active } of categoryPlan.setActive) await tx`update movement_categories set active = ${active} where id = ${id}`;
      const movementCategories = await lookup(tx, "movement_categories", "name");

      const productCategories = await lookup(tx, "product_categories", "lower(name)");
      const plan = buildPlan(
        legacy,
        { paymentMethods, units, movementCategories, productCategories },
        { importedAt: new Date().toISOString() } satisfies PlanOptions,
      );

      await insertRows(tx, "users", plan.users);
      await insertRows(tx, "product_categories", plan.productCategories);
      await insertRows(tx, "suppliers", plan.suppliers);
      await insertWithNumbers(tx, "products", plan.products);
      await insertRows(tx, "stock_levels", plan.stockLevels);
      await insertRows(tx, "recipe_components", plan.recipes);
      await insertRows(tx, "sale_orders", plan.saleOrders);
      await insertWithNumbers(tx, "movements", plan.movements);
      await insertRows(tx, "sale_order_lines", plan.saleOrderLines);

      const categoryNames = new Set(legacy.categoriasProducto.map((c) => String(c.nombre).trim().toLowerCase()));
      if (plan.productCategories.some((c) => String(c.name) === "General")) categoryNames.add("general");
      const reconciliation = await reconcile(tx, {
        legacy,
        plan,
        categoryPlan,
        referenceNames: {
          productCategories: [...categoryNames],
          paymentMethods: paymentNames,
          units: legacy.unidades.map((u) => String(u.codigo)),
          movementCategories: legacy.categorias
            .filter((c) => ["Ingreso", "Gasto", "Compra"].includes(String(c.tipo).trim()))
            .map((c) => String(c.nombre).trim()),
        },
      });
      const result: RunResult = {
        plan,
        reconciliation,
        skippedCategories: categoryPlan.skipped,
        categoriesInserted: categoryPlan.insert.length,
        categoriesActiveUpdated: categoryPlan.setActive.length,
        replaced,
        committed: false,
      };
      holder.value = result;
      // All or nothing: any mismatch (or --dry-run) rolls back everything, reference-data changes included.
      if (reconciliation.mismatches.length > 0) throw new DryRunRollback("reconciliation mismatch");
      if (options.dryRun) throw new DryRunRollback("dry run");
      await syncIdentity(tx, "products");
      await syncIdentity(tx, "movements");
      result.committed = true;
    });
  } catch (error) {
    if (!(error instanceof DryRunRollback)) throw error;
  }
  if (!holder.value) throw new Error("import produced no result");
  return holder.value;
}
